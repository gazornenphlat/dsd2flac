"""Copy the filter tables out of the original dsf2flac program into src/original_taps.py.

Usage: python tools/extract_taps.py <path to dsf2flac> src/original_taps.py

The addresses come from DsdDecimator's constructor (native_function_references_list
on 0x407000) and the tap counts from the initLookupTable calls (0x23f, 0xf0, 0x60).
Values are read as little-endian IEEE doubles, exactly as the program stores them.
"""

import struct
import sys

TABLES = [
    ("TAPS_88200", 0x5831E0, 575),    # DSD64 -> 88.2 kHz (decimate by 32)
    ("TAPS_176400", 0x582A60, 240),   # DSD64 -> 176.4 kHz (decimate by 16)
    ("TAPS_352800", 0x582760, 96),    # DSD64 -> 352.8 kHz (decimate by 8)
]


def file_offset(data: bytes, vaddr: int) -> int:
    """Map a virtual address to a file offset using the ELF program headers."""
    phoff = struct.unpack_from("<Q", data, 0x20)[0]
    phentsize, phnum = struct.unpack_from("<HH", data, 0x36)
    for i in range(phnum):
        p_type, _flags, p_off, p_vaddr, _paddr, p_filesz = struct.unpack_from(
            "<IIQQQQ", data, phoff + i * phentsize)
        if p_type == 1 and p_vaddr <= vaddr < p_vaddr + p_filesz:  # PT_LOAD
            return p_off + vaddr - p_vaddr
    raise ValueError(f"address 0x{vaddr:x} is not in a loaded segment")


def main() -> None:
    source, target = sys.argv[1], sys.argv[2]
    with open(source, "rb") as f:
        data = f.read()
    lines = ['"""Filter tables copied from the original dsf2flac (generated by tools/extract_taps.py)."""', ""]
    for name, vaddr, count in TABLES:
        taps = struct.unpack_from(f"<{count}d", data, file_offset(data, vaddr))
        lines.append(f"# {count} taps read from 0x{vaddr:x}")
        lines.append(f"{name} = (")
        for i in range(0, count, 4):
            lines.append("    " + ", ".join(repr(t) for t in taps[i:i + 4]) + ",")
        lines.append(")")
        lines.append("")
    with open(target, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("wrote", target)


if __name__ == "__main__":
    main()
